//! 语法分析模块：递归下降解析器。
//!
//! 接收词法器的记号流，产出 AST（见 ast.rs）。
//! 块结构由词法层的 缩进/缩出 记号表达，本层只关心文法本身。
//!
//! 错误恢复策略：语句级“跳到下一行”，争取一次编译尽量多地报告错误
//! （打印上限由诊断箱控制）；恢复过程中绝不越过 缩进/缩出，避免破坏块结构。

use crate::ast::{
    二元运算符, 表达式, 表达式种类, 程序, 函数定义, 语句, 语句种类, 类型,
};
use crate::error::{级别, 错误类别, 诊断箱};
use crate::lexer::{关键字, 记号, 记号种类};

/// 把记号流解析成程序。
pub fn 解析(记号流: Vec<记号>, 诊断: &mut 诊断箱) -> Result<程序, ()> {
    let mut 记号流 = 记号流;
    // 兜底：保证最后一个是 文件结束 记号
    if !matches!(记号流.last().map(|记号| &记号.种类), Some(记号种类::文件结束)) {
        let 行 = 记号流.last().map(|记号| 记号.行).unwrap_or(1);
        记号流.push(记号 {
            种类: 记号种类::文件结束,
            行,
            列: 1,
        });
    }
    let mut 解析器 = 解析器 {
        记号流,
        位置: 0,
        诊断,
        程序: 程序 {
            顶层语句: Vec::new(),
            函数列表: Vec::new(),
        },
        刚结束代码块: false,
    };
    解析器.解析程序()
}

struct 解析器<'a> {
    记号流: Vec<记号>,
    位置: usize,
    诊断: &'a mut 诊断箱,
    程序: 程序,
    /// 最近解析的语句/定义是否以缩进块收尾（块自己消费了末尾的 缩出，
    /// 此时语句后可以不再有 换行 记号）。
    刚结束代码块: bool,
}

impl<'a> 解析器<'a> {
    // ---------- 记号操作 ----------

    fn 当前(&self) -> &记号 {
        &self.记号流[self.位置]
    }

    fn 看(&self, 偏移: usize) -> &记号 {
        &self.记号流[(self.位置 + 偏移).min(self.记号流.len() - 1)]
    }

    fn 前进(&mut self) -> 记号 {
        let 记号 = self.记号流[self.位置].clone();
        if self.位置 < self.记号流.len() - 1 {
            self.位置 += 1;
        }
        记号
    }

    fn 是(&self, 种类: &记号种类) -> bool {
        &self.当前().种类 == 种类
    }

    fn 匹配(&mut self, 种类: &记号种类) -> bool {
        if self.是(种类) {
            self.前进();
            true
        } else {
            false
        }
    }

    fn 报错(&mut self, 消息: impl Into<String>) {
        let 记号 = self.当前();
        self.诊断.记录(级别::错误, 错误类别::语法, 消息, 记号.行, 记号.列);
    }

    fn 期望(&mut self, 种类: &记号种类, 描述: &str) -> Result<(), ()> {
        if self.是(种类) {
            self.前进();
            return Ok(());
        }
        self.报错(format!("期望{}，却遇到{}", 描述, 记号描述(&self.当前())));
        Err(())
    }

    fn 期望标识符(&mut self, 用途: &str) -> Result<String, ()> {
        match &self.当前().种类 {
            记号种类::标识符(名) => {
                let 名 = 名.clone();
                self.前进();
                Ok(名)
            }
            _ => {
                self.报错(format!("期望{}，却遇到{}", 用途, 记号描述(&self.当前())));
                Err(())
            }
        }
    }

    /// 语句级错误恢复：跳到本行结束（不越过 缩进/缩出）。
    fn 同步(&mut self) {
        while !matches!(
            self.当前().种类,
            记号种类::换行 | 记号种类::文件结束 | 记号种类::缩进 | 记号种类::缩出
        ) {
            self.前进();
        }
    }

    /// 类型记号：整数64 / 整数32 / 浮点数64 / 字符串 是标识符，空 是关键字。
    fn 是类型记号(&self) -> bool {
        记号转类型(&self.当前().种类).is_some()
    }

    fn 期望类型(&mut self) -> Result<类型, ()> {
        if let Some(类型) = 记号转类型(&self.当前().种类) {
            self.前进();
            Ok(类型)
        } else {
            self.报错(format!(
                "期望类型（整数64 / 整数32 / 浮点数64 / 字符串 / 空），却遇到{}",
                记号描述(&self.当前())
            ));
            Err(())
        }
    }

    // ---------- 程序与顶层 ----------

    fn 解析程序(&mut self) -> Result<程序, ()> {
        loop {
            if self.是(&记号种类::文件结束) {
                break;
            }
            if self.是(&记号种类::换行) {
                self.前进();
                continue;
            }
            if self.是(&记号种类::缩进) {
                self.报错("顶层的代码不允许缩进（只有函数体、分支与循环体才需要缩进）");
                // 必须先吞掉缩进记号，保证解析器持续推进：
                // 否则 报错→同步（同步不越过缩进）→循环 会在这里死循环，疯狂吃内存。
                self.前进();
                self.同步();
                continue;
            }
            if self.是(&记号种类::缩出) {
                self.报错("出现了多余的『缩出』（缩进不匹配）");
                self.前进();
                continue;
            }
            self.刚结束代码块 = false;
            // 函数定义判定：
            // 新写法：函数 类型 标识符 (参数)：；旧写法：类型 标识符 [类型 | ：] → 函数
            let 是函数定义 = self.是(&记号种类::关键字(关键字::函数))
                || (self.是类型记号()
                    && matches!(&self.看(1).种类, 记号种类::标识符(_))
                    && {
                        let 下下 = &self.看(2).种类;
                        下下 == &记号种类::冒号 || 记号转类型(下下).is_some()
                    });
            if 是函数定义 {
                let 解析结果 = if self.是(&记号种类::关键字(关键字::函数)) {
                    self.解析函数定义_函数形式()
                } else {
                    self.解析函数定义()
                };
                match 解析结果 {
                    Ok(函数) => self.程序.函数列表.push(函数),
                    Err(()) => self.刚结束代码块 = false,
                }
            } else {
                match self.解析语句() {
                    Ok(语句) => self.程序.顶层语句.push(语句),
                    Err(()) => self.刚结束代码块 = false,
                }
            }
            // ---- 语句终止符 ----
            if self.是(&记号种类::换行) {
                self.前进();
            } else if self.是(&记号种类::文件结束) {
                // 最后一条语句，无需终止符
            } else if self.刚结束代码块 {
                self.刚结束代码块 = false;
            } else {
                self.报错("一行只能写一条语句，语句结束后请换行");
                self.同步();
            }
        }
        Ok(std::mem::take(&mut self.程序))
    }

    /// 函数定义：返回类型 函数名 [类型 参数名, ...]：
    fn 解析函数定义(&mut self) -> Result<函数定义, ()> {
        let 定义行 = self.当前().行;
        let 返回类型 = self.期望类型()?;
        let 函数名 = self.期望标识符("函数名")?;
        let mut 参数: Vec<(类型, String)> = Vec::new();
        if !self.是(&记号种类::冒号) {
            loop {
                let 参数类型 = self.期望类型()?;
                let 参数名 = self.期望标识符("参数名")?;
                参数.push((参数类型, 参数名));
                if self.匹配(&记号种类::逗号) {
                    continue;
                }
                break;
            }
        }
        self.期望(&记号种类::冒号, "『：』（函数定义的参数列表之后）")?;
        self.期望(&记号种类::换行, "『：』之后的换行")?;
        let 函数体 = self.解析语句块("函数体")?;
        Ok(函数定义 {
            函数名,
            返回类型,
            参数,
            函数体,
            定义行,
        })
    }

    /// 函数定义（新写法，推荐）：函数 返回类型 函数名(参数列表)：
    /// 参数括号可省略（兼容旧风格 函数 返回类型 函数名 参数列表：）。
    fn 解析函数定义_函数形式(&mut self) -> Result<函数定义, ()> {
        let 定义行 = self.当前().行;
        self.前进(); // 函数
        let 返回类型 = self.期望类型()?;
        let 函数名 = self.期望标识符("函数名")?;
        let mut 参数: Vec<(类型, String)> = Vec::new();
        if self.是(&记号种类::左括号) {
            self.前进();
            if !self.是(&记号种类::右括号) {
                loop {
                    let 参数类型 = self.期望类型()?;
                    let 参数名 = self.期望标识符("参数名")?;
                    参数.push((参数类型, 参数名));
                    if self.匹配(&记号种类::逗号) {
                        continue;
                    }
                    break;
                }
            }
            self.期望(&记号种类::右括号, "『）』（函数参数列表）")?;
        } else if !self.是(&记号种类::冒号) {
            // 兼容不带括号的参数列表
            loop {
                let 参数类型 = self.期望类型()?;
                let 参数名 = self.期望标识符("参数名")?;
                参数.push((参数类型, 参数名));
                if self.匹配(&记号种类::逗号) {
                    continue;
                }
                break;
            }
        }
        self.期望(&记号种类::冒号, "『：』（函数定义的参数列表之后）")?;
        self.期望(&记号种类::换行, "『：』之后的换行")?;
        let 函数体 = self.解析语句块("函数体")?;
        Ok(函数定义 {
            函数名,
            返回类型,
            参数,
            函数体,
            定义行,
        })
    }

    /// 缩进语句块：缩进 { 语句 } 缩出。
    fn 解析语句块(&mut self, 用途: &str) -> Result<Vec<语句>, ()> {
        if !self.是(&记号种类::缩进) {
            self.报错(format!(
                "『{}』缺少缩进的语句块（：之后请换行，并用 4 个空格缩进）",
                用途
            ));
            return Err(());
        }
        self.前进();
        let mut 块 = Vec::new();
        loop {
            if self.是(&记号种类::文件结束) {
                self.报错("文件在语句块内意外结束，请检查缩进是否完整");
                break;
            }
            if self.是(&记号种类::换行) {
                self.前进();
                continue;
            }
            if self.是(&记号种类::缩出) {
                self.前进();
                self.刚结束代码块 = true;
                break;
            }
            if self.是(&记号种类::缩进) {
                self.报错("此处出现了多余的缩进（可能多缩进了一层）");
                self.前进();
                continue;
            }
            self.刚结束代码块 = false;
            match self.解析语句() {
                Ok(语句) => 块.push(语句),
                Err(()) => self.刚结束代码块 = false,
            }
            // ---- 语句终止符 ----
            if self.是(&记号种类::换行) {
                self.前进();
            } else if self.是(&记号种类::缩出) {
                self.前进();
                self.刚结束代码块 = true;
                break;
            } else if self.是(&记号种类::文件结束) {
                self.报错("文件在语句块内意外结束，请检查缩进是否完整");
                break;
            } else if self.刚结束代码块 {
                self.刚结束代码块 = false;
            } else {
                self.报错("一行只能写一条语句，语句结束后请换行");
                self.同步();
            }
        }
        Ok(块)
    }

    // ---------- 语句 ----------

    fn 解析语句(&mut self) -> Result<语句, ()> {
        let 行 = self.当前().行;
        match &self.当前().种类 {
            记号种类::关键字(关键字::设) => {
                self.前进();
                let 变量名 = self.期望标识符("变量名")?;
                self.期望(&记号种类::关键字(关键字::为), "『为』（设 变量名 为 表达式）")?;
                let 初值 = self.解析表达式()?;
                Ok(语句 {
                    种类: 语句种类::设 {
                        变量名,
                        初值: Box::new(初值),
                    },
                    行,
                })
            }
            记号种类::关键字(关键字::打印) => {
                self.前进();
                let (参数, 换行) = self.解析打印参数()?;
                Ok(语句 {
                    种类: 语句种类::打印 { 参数, 换行 },
                    行,
                })
            }
            记号种类::关键字(关键字::返回) => {
                self.前进();
                if self.是(&记号种类::换行)
                    || self.是(&记号种类::缩出)
                    || self.是(&记号种类::文件结束)
                {
                    return Ok(语句 {
                        种类: 语句种类::返回(None),
                        行,
                    });
                }
                let 表达式 = self.解析表达式()?;
                Ok(语句 {
                    种类: 语句种类::返回(Some(Box::new(表达式))),
                    行,
                })
            }
            记号种类::关键字(关键字::如果) => {
                self.前进();
                self.解析如果(行)
            }
            记号种类::关键字(关键字::当) => {
                self.前进();
                self.解析当(行)
            }
            记号种类::关键字(关键字::跳出) => {
                self.前进();
                Ok(语句 {
                    种类: 语句种类::跳出,
                    行,
                })
            }
            记号种类::关键字(关键字::跳过) => {
                self.前进();
                Ok(语句 {
                    种类: 语句种类::跳过,
                    行,
                })
            }
            记号种类::关键字(关键字::重复) => {
                self.前进();
                let 次数 = self.解析表达式()?;
                self.期望(&记号种类::关键字(关键字::次), "『次』（重复 N 次：）")?;
                self.期望(&记号种类::冒号, "『：』（重复 N 次：）")?;
                self.期望(&记号种类::换行, "『：』之后的换行")?;
                let 循环体 = self.解析语句块("『重复』的循环体")?;
                Ok(语句 {
                    种类: 语句种类::重复 {
                        次数: Box::new(次数),
                        循环体,
                    },
                    行,
                })
            }
            记号种类::关键字(关键字::否则) => {
                self.报错("『否则』必须与对应的『如果』处于同一缩进层级，并且紧跟在它的语句块之后");
                Err(())
            }
            记号种类::关键字(关键字::函数) => {
                self.报错("函数只能在文件的顶层定义（格式：函数 返回类型 函数名(参数列表)：）");
                Err(())
            }
            记号种类::关键字(关键字::导入) => {
                self.报错("『导入』必须单独占一行，格式：导入 \"文件名.jy\"（引号内是相对路径）");
                Err(())
            }
            记号种类::关键字(关键字::空) => {
                self.报错("『空』只能用作函数的返回类型，不能出现在语句开头");
                Err(())
            }
            记号种类::关键字(关键字::真)
            | 记号种类::关键字(关键字::假)
            | 记号种类::关键字(关键字::为) => {
                self.报错("关键字不能出现在语句开头");
                Err(())
            }
            记号种类::标识符(_) if 记号转类型(&self.当前().种类).is_some() => {
                // 带类型声明：类型 变量名 = 表达式（demo 中的写法）
                let 类型 = 记号转类型(&self.当前().种类).unwrap();
                self.前进();
                let 变量名 = self.期望标识符("变量名")?;
                if self.是(&记号种类::冒号) || 记号转类型(&self.当前().种类).is_some() {
                    self.报错("函数只能在文件的顶层定义，不能写在语句块内部");
                    return Err(());
                }
                self.期望(&记号种类::赋值, "『=』（类型 变量名 = 表达式）")?;
                let 初值 = self.解析表达式()?;
                Ok(语句 {
                    种类: 语句种类::带类型声明 {
                        类型,
                        变量名,
                        初值: Box::new(初值),
                    },
                    行,
                })
            }
            记号种类::标识符(名) => {
                let 名 = 名.clone();
                // 复合赋值：名 += 表达式 等（语句级，不是表达式）
                if let Some(运算符) = 复合赋值运算符(&self.看(1).种类) {
                    if self.看(2).种类 == 记号种类::赋值 {
                        self.前进();
                        self.前进();
                        self.前进();
                        let 值 = self.解析表达式()?;
                        return Ok(语句 {
                            种类: 语句种类::赋值 {
                                变量名: 名,
                                值: Box::new(值),
                                运算符: Some(运算符),
                            },
                            行,
                        });
                    }
                }
                if self.看(1).种类 == 记号种类::赋值 {
                    // 赋值语句：变量名 = 表达式
                    self.前进();
                    self.前进();
                    let 值 = self.解析表达式()?;
                    return Ok(语句 {
                        种类: 语句种类::赋值 {
                            变量名: 名,
                            值: Box::new(值),
                            运算符: None,
                        },
                        行,
                    });
                }
                // 否则按表达式语句处理（第一版只允许函数调用）
                self.解析表达式语句(行)
            }
            _ => self.解析表达式语句(行),
        }
    }

    /// 打印 的参数表：0 个参数（只换行）或逗号分隔的多个表达式。
    /// 打印(...) 与 打印 ... 完全等价：下一个记号是 ( 时无条件按参数列表解析；
    /// 结尾的关键字 不换行 取消末尾换行。
    fn 解析打印参数(&mut self) -> Result<(Vec<表达式>, bool), ()> {
        let mut 参数 = Vec::new();
        if self.是(&记号种类::左括号) {
            // 括号形式：打印(1, 2) / 打印 (1, 2) / 打印()
            self.前进();
            if !self.是(&记号种类::右括号) {
                参数.push(self.解析表达式()?);
                while self.匹配(&记号种类::逗号) {
                    参数.push(self.解析表达式()?);
                }
            }
            self.期望(&记号种类::右括号, "『）』（打印 的参数列表）")?;
        } else if !self.是(&记号种类::换行)
            && !self.是(&记号种类::缩出)
            && !self.是(&记号种类::文件结束)
        {
            参数.push(self.解析表达式()?);
            while self.匹配(&记号种类::逗号) {
                参数.push(self.解析表达式()?);
            }
        }
        // 不换行 关键字取消末尾换行
        let 换行 = !self.匹配(&记号种类::关键字(关键字::不换行));
        Ok((参数, 换行))
    }

    /// 如果 条件： / 否则： / 否则如果 条件：（语法糖，展开成嵌套 如果）
    fn 解析如果(&mut self, 行: usize) -> Result<语句, ()> {
        let 条件 = self.解析表达式()?;
        self.期望(&记号种类::冒号, "『：』（如果 条件：）")?;
        self.期望(&记号种类::换行, "『：』之后的换行")?;
        let 分支 = self.解析语句块("『如果』的语句块")?;
        let 否则分支 = self.解析否则链()?;
        Ok(语句 {
            种类: 语句种类::如果 {
                条件: Box::new(条件),
                分支,
                否则分支,
            },
            行,
        })
    }

    /// 解析 否则 / 否则如果 链。
    /// 否则如果 条件： 等价于 否则： 如果 条件：，直接展开成嵌套的 如果 语句，
    /// 语义分析与代码生成完全不用感知它。
    fn 解析否则链(&mut self) -> Result<Vec<语句>, ()> {
        if !self.是(&记号种类::关键字(关键字::否则)) {
            return Ok(Vec::new());
        }
        let 行 = self.当前().行;
        self.前进();
        if self.是(&记号种类::关键字(关键字::如果)) {
            self.前进();
            let 条件 = self.解析表达式()?;
            self.期望(&记号种类::冒号, "『：』（否则如果 条件：）")?;
            self.期望(&记号种类::换行, "『：』之后的换行")?;
            let 分支 = self.解析语句块("『否则如果』的语句块")?;
            let 尾部 = self.解析否则链()?;
            Ok(vec![语句 {
                种类: 语句种类::如果 {
                    条件: Box::new(条件),
                    分支,
                    否则分支: 尾部,
                },
                行,
            }])
        } else {
            self.期望(&记号种类::冒号, "『：』（否则：）")?;
            self.期望(&记号种类::换行, "『：』之后的换行")?;
            self.解析语句块("『否则』的语句块")
        }
    }

    /// 当 条件：
    fn 解析当(&mut self, 行: usize) -> Result<语句, ()> {
        let 条件 = self.解析表达式()?;
        self.期望(&记号种类::冒号, "『：』（当 条件：）")?;
        self.期望(&记号种类::换行, "『：』之后的换行")?;
        let 循环体 = self.解析语句块("『当』的循环体")?;
        Ok(语句 {
            种类: 语句种类::当 {
                条件: Box::new(条件),
                循环体,
            },
            行,
        })
    }

    /// 表达式语句：第一版只允许函数调用。
    fn 解析表达式语句(&mut self, 行: usize) -> Result<语句, ()> {
        let 表达式 = self.解析表达式()?;
        if matches!(&表达式.种类, 表达式种类::调用 { .. }) {
            Ok(语句 {
                种类: 语句种类::表达式语句(Box::new(表达式)),
                行,
            })
        } else {
            self.诊断.记录(
                级别::错误,
                错误类别::语法,
                "第一版的表达式语句只支持函数调用（例如 阶乘(5)），计算结果请用 设/打印 处理",
                行,
                1,
            );
            Err(())
        }
    }

    // ---------- 表达式（优先级：或 > 与 > 比较 > 加减 > 乘除 > 取负/非 > 原子） ----------

    fn 解析表达式(&mut self) -> Result<表达式, ()> {
        self.解析或()
    }

    /// 逻辑或（|| / 或）：优先级最低的二元运算，左结合。
    fn 解析或(&mut self) -> Result<表达式, ()> {
        let mut 左 = self.解析与()?;
        loop {
            if !self.是(&记号种类::或) {
                break;
            }
            let 行 = self.当前().行;
            let 列 = self.当前().列;
            self.前进();
            let 右 = self.解析与()?;
            左 = 表达式 {
                种类: 表达式种类::逻辑或 {
                    左: Box::new(左),
                    右: Box::new(右),
                },
                行,
                列,
            };
        }
        Ok(左)
    }

    /// 逻辑与（&& / 与）：左结合。
    fn 解析与(&mut self) -> Result<表达式, ()> {
        let mut 左 = self.解析比较()?;
        loop {
            if !self.是(&记号种类::且) {
                break;
            }
            let 行 = self.当前().行;
            let 列 = self.当前().列;
            self.前进();
            let 右 = self.解析比较()?;
            左 = 表达式 {
                种类: 表达式种类::逻辑且 {
                    左: Box::new(左),
                    右: Box::new(右),
                },
                行,
                列,
            };
        }
        Ok(左)
    }

    /// 比较：非结合（不支持 a < b < c 连续比较）。
    fn 解析比较(&mut self) -> Result<表达式, ()> {
        let 行 = self.当前().行;
        let 列 = self.当前().列;
        let 左 = self.解析加减()?;
        let 运算符 = match &self.当前().种类 {
            记号种类::大于 => Some(二元运算符::大于),
            记号种类::小于 => Some(二元运算符::小于),
            记号种类::大于等于 => Some(二元运算符::大于等于),
            记号种类::小于等于 => Some(二元运算符::小于等于),
            记号种类::等于 => Some(二元运算符::等于),
            记号种类::不等于 => Some(二元运算符::不等于),
            _ => None,
        };
        if let Some(运算符) = 运算符 {
            self.前进();
            let 右 = self.解析加减()?;
            if matches!(
                self.当前().种类,
                记号种类::大于
                    | 记号种类::小于
                    | 记号种类::大于等于
                    | 记号种类::小于等于
                    | 记号种类::等于
                    | 记号种类::不等于
            ) {
                self.报错("第一版不支持连续比较（如 a < b < c），请拆开写");
                return Err(());
            }
            return Ok(表达式 {
                种类: 表达式种类::二元 {
                    运算符,
                    左: Box::new(左),
                    右: Box::new(右),
                },
                行,
                列,
            });
        }
        Ok(左)
    }

    fn 解析加减(&mut self) -> Result<表达式, ()> {
        let mut 左 = self.解析乘除()?;
        loop {
            let 运算符 = match &self.当前().种类 {
                记号种类::加 => Some(二元运算符::加),
                记号种类::减 => Some(二元运算符::减),
                _ => None,
            };
            let Some(运算符) = 运算符 else { break };
            let 行 = self.当前().行;
            let 列 = self.当前().列;
            self.前进();
            let 右 = self.解析乘除()?;
            左 = 表达式 {
                种类: 表达式种类::二元 {
                    运算符,
                    左: Box::new(左),
                    右: Box::new(右),
                },
                行,
                列,
            };
        }
        Ok(左)
    }

    fn 解析乘除(&mut self) -> Result<表达式, ()> {
        let mut 左 = self.解析一元()?;
        loop {
            let 运算符 = match &self.当前().种类 {
                记号种类::乘 => Some(二元运算符::乘),
                记号种类::除 => Some(二元运算符::除),
                记号种类::取余 => Some(二元运算符::取余),
                _ => None,
            };
            let Some(运算符) = 运算符 else { break };
            let 行 = self.当前().行;
            let 列 = self.当前().列;
            self.前进();
            let 右 = self.解析一元()?;
            左 = 表达式 {
                种类: 表达式种类::二元 {
                    运算符,
                    左: Box::new(左),
                    右: Box::new(右),
                },
                行,
                列,
            };
        }
        Ok(左)
    }

    fn 解析一元(&mut self) -> Result<表达式, ()> {
        if self.是(&记号种类::非) {
            let 行 = self.当前().行;
            let 列 = self.当前().列;
            self.前进();
            let 内 = self.解析一元()?;
            return Ok(表达式 {
                种类: 表达式种类::逻辑非(Box::new(内)),
                行,
                列,
            });
        }
        if self.是(&记号种类::减) {
            let 行 = self.当前().行;
            let 列 = self.当前().列;
            self.前进();
            let 内 = self.解析一元()?;
            return Ok(表达式 {
                种类: 表达式种类::取负(Box::new(内)),
                行,
                列,
            });
        }
        self.解析原子()
    }

    fn 解析原子(&mut self) -> Result<表达式, ()> {
        let 行 = self.当前().行;
        let 列 = self.当前().列;
        match &self.当前().种类 {
            记号种类::整数(值) => {
                let 值 = *值;
                self.前进();
                Ok(表达式 {
                    种类: 表达式种类::整数字面量(值),
                    行,
                    列,
                })
            }
            记号种类::浮点数(值) => {
                let 值 = *值;
                self.前进();
                Ok(表达式 {
                    种类: 表达式种类::浮点字面量(值),
                    行,
                    列,
                })
            }
            记号种类::字符串(值) => {
                let 值 = 值.clone();
                self.前进();
                Ok(表达式 {
                    种类: 表达式种类::字符串字面量(值),
                    行,
                    列,
                })
            }
            记号种类::关键字(关键字::真) => {
                self.前进();
                Ok(表达式 {
                    种类: 表达式种类::真,
                    行,
                    列,
                })
            }
            记号种类::关键字(关键字::假) => {
                self.前进();
                Ok(表达式 {
                    种类: 表达式种类::假,
                    行,
                    列,
                })
            }
            记号种类::关键字(关键字::空) => {
                self.报错("『空』只能用作函数的返回类型，不能作为表达式");
                Err(())
            }
            记号种类::标识符(名) => {
                let 名 = 名.clone();
                self.前进();
                if self.匹配(&记号种类::左括号) {
                    // 函数调用：名(参数, ...)
                    let mut 参数 = Vec::new();
                    if !self.是(&记号种类::右括号) {
                        loop {
                            参数.push(self.解析表达式()?);
                            if self.匹配(&记号种类::逗号) {
                                continue;
                            }
                            break;
                        }
                    }
                    self.期望(&记号种类::右括号, "『）』（调用参数列表之后）")?;
                    Ok(表达式 {
                        种类: 表达式种类::调用 { 函数名: 名, 参数 },
                        行,
                        列,
                    })
                } else {
                    Ok(表达式 {
                        种类: 表达式种类::变量(名),
                        行,
                        列,
                    })
                }
            }
            记号种类::左括号 => {
                self.前进();
                let 内 = self.解析表达式()?;
                self.期望(&记号种类::右括号, "『）』")?;
                Ok(内)
            }
            _ => {
                self.报错(format!("期望一个表达式，却遇到{}", 记号描述(&self.当前())));
                Err(())
            }
        }
    }
}

/// 记号种类 → 简言类型（整数64 等是标识符，空 是关键字）。
/// 推荐写法：整数（= 整数64）、小数（= 浮点数64）、布尔、字符串、空；
/// 整数64/整数32/浮点数64/浮点64/小数64 均为兼容别名。
fn 记号转类型(种类: &记号种类) -> Option<类型> {
    Some(match 种类 {
        记号种类::标识符(名) => match 名.as_str() {
            "整数" | "整数64" => 类型::整数64,
            "整数32" => 类型::整数32,
            "小数" | "浮点数64" | "浮点64" | "小数64" => 类型::浮点数64,
            "字符串" => 类型::字符串,
            "布尔" => 类型::布尔,
            _ => return None,
        },
        记号种类::关键字(关键字::空) => 类型::空,
        _ => return None,
    })
}

/// 复合赋值运算符：+ - * / % 后面紧跟 = 时，表示 += 等（语句级）。
fn 复合赋值运算符(种类: &记号种类) -> Option<二元运算符> {
    Some(match 种类 {
        记号种类::加 => 二元运算符::加,
        记号种类::减 => 二元运算符::减,
        记号种类::乘 => 二元运算符::乘,
        记号种类::除 => 二元运算符::除,
        记号种类::取余 => 二元运算符::取余,
        _ => return None,
    })
}

/// 把记号描述成人类可读的中文（用于报错消息）。
fn 记号描述(记号: &记号) -> String {
    match &记号.种类 {
        记号种类::关键字(关键字) => format!("关键字『{}』", 关键字.文本()),
        记号种类::标识符(名) => format!("标识符『{}』", 名),
        记号种类::整数(值) => format!("整数『{}』", 值),
        记号种类::浮点数(值) => format!("浮点数『{}』", 值),
        记号种类::字符串(值) => format!("字符串“{}”", 值),
        记号种类::加 => "『+』".to_string(),
        记号种类::减 => "『-』".to_string(),
        记号种类::乘 => "『*』".to_string(),
        记号种类::除 => "『/』".to_string(),
        记号种类::取余 => "『%』".to_string(),
        记号种类::赋值 => "『=』".to_string(),
        记号种类::大于 => "『>』".to_string(),
        记号种类::小于 => "『<』".to_string(),
        记号种类::大于等于 => "『>=』".to_string(),
        记号种类::小于等于 => "『<=』".to_string(),
        记号种类::等于 => "『==』".to_string(),
        记号种类::不等于 => "『!=』".to_string(),
        记号种类::且 => "『&&』".to_string(),
        记号种类::或 => "『||』".to_string(),
        记号种类::非 => "『!』".to_string(),
        记号种类::逗号 => "『，』".to_string(),
        记号种类::冒号 => "『：』".to_string(),
        记号种类::左括号 => "『（』".to_string(),
        记号种类::右括号 => "『）』".to_string(),
        记号种类::换行 => "行尾".to_string(),
        记号种类::缩进 => "缩进".to_string(),
        记号种类::缩出 => "缩出".to_string(),
        记号种类::文件结束 => "文件结束".to_string(),
    }
}
