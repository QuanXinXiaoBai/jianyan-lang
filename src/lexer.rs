//! 词法分析模块：把源码文本切成记号流。
//!
//! 除了常规的词法分析（标识符/数字/字符串/注释/标点），还承担三项
//! 【简言】特色职责：
//!
//! 1. **缩进语法**：固定 4 空格为一层缩进，本模块生成 `缩进`/`缩出` 记号
//!    （思路同 Python）；制表符、非 4 倍数的缩进、缩回不到的层级，
//!    一律报带行号的【缩进错误】。
//! 2. **中文比较词别名**：小于 / 大于 / 小于等于 / 大于等于 / 等于 / 不等于
//!    直接映射成与符号形式（< > <= >= == !=）完全相同的记号，解析器无需
//!    区分两种写法；同理，逻辑运算的中文别名 与 / 或 / 非 映射为 && / || / !。
//! 3. **全角标点归一化**：： ， （ ） 与全角空格按半角处理；中文弯引号
//!    “ ” 与直引号 " 一样作为字符串字面量的定界符，方便中文输入法书写。
//!
//! 括号内的换行不产生 换行 记号（允许调用参数跨行书写）。

use crate::error::{级别, 错误类别, 诊断箱};

/// 简言关键字（全部中文，大小写敏感，仅全字匹配）。
/// 其中 设/为 用于声明语句；函数/导入 为保留字（第一版语法中不出现）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 关键字 {
    如果,
    否则,
    当,
    函数,
    返回,
    打印,
    导入,
    真,
    假,
    空,
    设,
    为,
    跳出,
    跳过,
    重复,
    次,
    不换行,
}

