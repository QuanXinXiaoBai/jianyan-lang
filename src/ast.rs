//! 抽象语法树（AST）定义。
//!
//! 语法树是词法、语法与语义、代码生成之间的桥梁：
//! 词法器不认识它，解析器负责构造它，语义分析与汇编生成负责消费它。
//! 每个表达式/语句都携带行号（虚拟行号，错误报告阶段会翻译回真实文件与行号）。

/// 简言第一版的类型系统。
///
/// 注意：布尔值（真/假）底层映射为整数 1/0，这里单独列出布尔只是为了让
/// 报错与代码生成时能区分来源，运算时一律按 64 位整数处理。
/// 整数32 第一版简化实现：与 整数64 一样按 64 位槽位存放。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 类型 {
    整数64,
    整数32,
    浮点数64,
    字符串,
    空,
    布尔,
}

impl 类型 {
    /// 类型的简言写法，用于报错消息。
    pub fn 名字(self) -> &'static str {
        match self {
            类型::整数64 => "整数64",
            类型::整数32 => "整数32",
            类型::浮点数64 => "浮点数64",
            类型::字符串 => "字符串",
            类型::空 => "空",
            类型::布尔 => "布尔",
        }
    }
}

/// 二元运算符。中文比较词（小于、大于、小于等于……）在词法阶段就已经
/// 归一化成与符号形式（<、>、<=……）相同的记号，这里只有一套表示。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 二元运算符 {
    加,
    减,
    乘,
    除,
    取余,
    大于,
    小于,
    大于等于,
    小于等于,
    等于,
    不等于,
}

impl 二元运算符 {
    /// 运算符的符号写法（用于注释与报错）。
    pub fn 符号(self) -> &'static str {
        match self {
            二元运算符::加 => "+",
            二元运算符::减 => "-",
            二元运算符::乘 => "*",
            二元运算符::除 => "/",
            二元运算符::取余 => "%",
            二元运算符::大于 => ">",
            二元运算符::小于 => "<",
            二元运算符::大于等于 => ">=",
            二元运算符::小于等于 => "<=",
            二元运算符::等于 => "==",
            二元运算符::不等于 => "!=",
        }
    }

    /// 是否是比较运算符（比较的结果是布尔值）。
    pub fn 是比较(self) -> bool {
        matches!(
            self,
            二元运算符::大于
                | 二元运算符::小于
                | 二元运算符::大于等于
                | 二元运算符::小于等于
                | 二元运算符::等于
                | 二元运算符::不等于
        )
    }
}

/// 表达式（带行号与列号，便于语义错误报告具体位置）。
#[derive(Debug, Clone)]
pub struct 表达式 {
    pub 种类: 表达式种类,
    pub 行: usize,
    pub 列: usize,
}

#[derive(Debug, Clone)]
pub enum 表达式种类 {
    整数字面量(i64),
    浮点字面量(f64),
    字符串字面量(String),
    真,
    假,
    变量(String),
    二元 {
        运算符: 二元运算符,
        左: Box<表达式>,
        右: Box<表达式>,
    },
    取负(Box<表达式>),
    /// 逻辑与（&& / 与）：短路求值，结果 0/1
    逻辑且 {
        左: Box<表达式>,
        右: Box<表达式>,
    },
    /// 逻辑或（|| / 或）：短路求值，结果 0/1
    逻辑或 {
        左: Box<表达式>,
        右: Box<表达式>,
    },
    /// 逻辑非（! / 非）：结果 0/1
    逻辑非(Box<表达式>),
    调用 {
        函数名: String,
        参数: Vec<表达式>,
    },
}

/// 语句（同样带行号）。
#[derive(Debug, Clone)]
pub struct 语句 {
    pub 种类: 语句种类,
    pub 行: usize,
}

#[derive(Debug, Clone)]
pub enum 语句种类 {
    /// 设 变量名 为 表达式（类型由初值推断）
    设 {
        变量名: String,
        初值: Box<表达式>,
    },
    /// 类型 变量名 = 表达式（demo 中的声明写法）
    带类型声明 {
        类型: 类型,
        变量名: String,
        初值: Box<表达式>,
    },
    /// 变量名 = 表达式（给已有变量赋值）；运算符为 Some 时是复合赋值 += 等
    赋值 {
        变量名: String,
        值: Box<表达式>,
        运算符: Option<二元运算符>,
    },
    /// 打印 表达式, 表达式, ...（0 个参数 = 打印一个空行；
    /// 多个参数同一行依次输出、无分隔符；换行=false 时不输出末尾换行）
    打印 {
        参数: Vec<表达式>,
        换行: bool,
    },
    /// 跳出：立即退出所在循环
    跳出,
    /// 跳过：跳过本次循环剩余部分，进入下一次迭代
    跳过,
    /// 重复 N 次：（计数循环）
    重复 {
        次数: Box<表达式>,
        循环体: Vec<语句>,
    },
    /// 返回 [表达式]
    返回(Option<Box<表达式>>),
    /// 如果 条件： / 否则：
    如果 {
        条件: Box<表达式>,
        分支: Vec<语句>,
        否则分支: Vec<语句>,
    },
    /// 当 条件：
    当 {
        条件: Box<表达式>,
        循环体: Vec<语句>,
    },
    /// 函数调用作为一条语句（第一版表达式语句只允许调用）
    表达式语句(Box<表达式>),
}

/// 函数定义：返回类型 函数名 参数列表：
/// （第一版不使用 函数 关键字，参数没有括号，冒号后是缩进块）
#[derive(Debug, Clone)]
pub struct 函数定义 {
    pub 函数名: String,
    pub 返回类型: 类型,
    pub 参数: Vec<(类型, String)>,
    pub 函数体: Vec<语句>,
    pub 定义行: usize,
}

/// 整个程序：顶层语句（将被编译器包裹进自动生成的入口 main）+ 函数列表。
#[derive(Debug, Clone, Default)]
pub struct 程序 {
    pub 顶层语句: Vec<语句>,
    pub 函数列表: Vec<函数定义>,
}
