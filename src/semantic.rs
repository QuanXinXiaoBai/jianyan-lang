//! 语义分析模块：编译期的静态检查与符号表构建。
//!
//! 第一版（与语言规范一一对应）的检查项：
//! 1. 变量是否存在 —— 使用未定义的变量 / 给未定义的变量赋值 → 报【变量未定义】；
//! 2. 函数是否存在 —— 调用不存在的函数 → 报【未定义的函数】；
//! 3. 参数数量 —— 实参个数与形参个数不一致 → 报【参数数量不匹配】；
//! 4. 符号重复定义 —— 同名函数、同作用域同名变量、同名参数 → 报【符号重复定义】；
//! 5. 返回语句 —— 返回类型为 空 的函数不允许 返回 带值的表达式；
//! 6. 类型相容 —— 字符串不参与算术/比较运算，不能作为 如果/当 的条件，
//!    字符串与数值之间不能互相赋值/传参（整数与浮点之间会自动转换）。
//!
//! 分析产物是一张符号表（函数签名 + 每个作用域内变量的声明顺序与类型），
//! 汇编生成阶段依赖它来分配栈槽位、选择整数/浮点指令。

use std::collections::HashMap;

use crate::ast::{二元运算符, 表达式, 表达式种类, 程序, 语句, 语句种类, 类型};
use crate::error::{级别, 错误类别, 诊断箱};

/// 函数的签名信息。
#[derive(Debug, Clone)]
pub struct 函数信息 {
    pub 返回类型: 类型,
    pub 参数类型: Vec<类型>,
    pub 定义行: usize,
}

/// 一个作用域：变量声明顺序（决定栈槽位顺序，参数在前）+ 名字到类型与声明行的映射。
#[derive(Debug, Clone, Default)]
pub struct 作用域 {
    pub 顺序: Vec<String>,
    pub 类型表: HashMap<String, 类型>,
    pub 声明行: HashMap<String, usize>,
}

/// 语义分析的产物。
#[derive(Debug, Clone)]
pub struct 语义结果 {
    pub 函数表: HashMap<String, 函数信息>,
    pub 入口作用域: 作用域,
    pub 函数作用域表: HashMap<String, 作用域>,
}

/// 对整个程序做语义检查；有错误时返回 Err。
pub fn 分析(程序: &程序, 诊断: &mut 诊断箱) -> Result<语义结果, ()> {
    let mut 结果 = 语义结果 {
        函数表: HashMap::new(),
        入口作用域: 作用域::default(),
        函数作用域表: HashMap::new(),
    };
    // ---- 第一遍：收集全部函数定义，检查【符号重复定义】 ----
    for 函数 in &程序.函数列表 {
        if let Some(旧信息) = 结果.函数表.get(&函数.函数名) {
            诊断.记录(
                级别::错误,
                错误类别::语义,
                format!(
                    "【符号重复定义】函数『{}』重复定义（先前定义在第 {} 行）",
                    函数.函数名, 旧信息.定义行
                ),
                函数.定义行,
                1,
            );
        } else {
            结果.函数表.insert(
                函数.函数名.clone(),
                函数信息 {
                    返回类型: 函数.返回类型,
                    参数类型: 函数.参数.iter().map(|(类型, _)| *类型).collect(),
                    定义行: 函数.定义行,
                },
            );
        }
    }
    // ---- 入口（顶层语句将被包裹进自动生成的 main）：返回类型按 整数64 处理 ----
    let mut 入口作用域 = 作用域::default();
    检查语句块(
        &程序.顶层语句,
        &mut 入口作用域,
        &结果.函数表,
        "入口（main）",
        类型::整数64,
        0,
        诊断,
    );
    结果.入口作用域 = 入口作用域;
    // ---- 逐个函数 ----
    for 函数 in &程序.函数列表 {
        let mut 函数作用域 = 作用域::default();
        for (参数类型, 参数名) in &函数.参数 {
            if 函数作用域.类型表.contains_key(参数名) {
                诊断.记录(
                    级别::错误,
                    错误类别::语义,
                    format!(
                        "【符号重复定义】函数『{}』的参数『{}』重复定义",
                        函数.函数名, 参数名
                    ),
                    函数.定义行,
                    1,
                );
            } else {
                函数作用域.顺序.push(参数名.clone());
                函数作用域.类型表.insert(参数名.clone(), *参数类型);
                函数作用域.声明行.insert(参数名.clone(), 函数.定义行);
            }
        }
        检查语句块(
            &函数.函数体,
            &mut 函数作用域,
            &结果.函数表,
            &函数.函数名,
            函数.返回类型,
            0,
            诊断,
        );
        // ---- 函数末尾缺少 返回 的提示 ----
        if 函数.返回类型 != 类型::空 && !函数体以返回结尾(&函数.函数体) {
            诊断.记录(
                级别::警告,
                错误类别::语义,
                format!(
                    "函数『{}』可能没有返回值（声明返回类型为 {}，请在末尾补上 返回 语句）",
                    函数.函数名,
                    函数.返回类型.名字()
                ),
                函数.定义行,
                1,
            );
        }
        结果.函数作用域表.insert(函数.函数名.clone(), 函数作用域);
    }
    if 诊断.有错误() {
        Err(())
    } else {
        Ok(结果)
    }
}

/// 函数体的最后一条语句是否是 返回。
fn 函数体以返回结尾(体: &[语句]) -> bool {
    matches!(体.last().map(|语句| &语句.种类), Some(语句种类::返回(_)))
}

/// 检查一个语句块（顶层或函数体）：逐条语句做作用域与类型检查。
/// `循环深度` 用于校验 跳出/跳过 只能在循环内部出现。
#[allow(clippy::too_many_arguments)]
fn 检查语句块(
    块: &[语句],
    作用域: &mut 作用域,
    函数表: &HashMap<String, 函数信息>,
    所在函数: &str,
    返回类型: 类型,
    循环深度: usize,
    诊断: &mut 诊断箱,
) {
    for 语句 in 块 {
        match &语句.种类 {
            语句种类::设 { 变量名, 初值 } => {
                let 初值类型 = 检查表达式(初值, 作用域, 函数表, 诊断);
                声明变量(作用域, 变量名, 初值类型, 语句.行, 诊断);
            }
            语句种类::带类型声明 {
                类型,
                变量名,
                初值,
            } => {
                let 初值类型 = 检查表达式(初值, 作用域, 函数表, 诊断);
                检查可赋值(初值类型, *类型, 语句.行, 诊断);
                声明变量(作用域, 变量名, *类型, 语句.行, 诊断);
            }
            语句种类::赋值 {
                变量名,
                值,
                运算符,
            } => {
                let 值类型 = 检查表达式(值, 作用域, 函数表, 诊断);
                match 作用域.类型表.get(变量名) {
                    None => 诊断.记录(
                        级别::错误,
                        错误类别::语义,
                        format!(
                            "【变量未定义】给未定义的变量『{}』赋值（请先使用 设 变量名 为 表达式 声明）",
                            变量名
                        ),
                        语句.行,
                        1,
                    ),
                    Some(&现有类型) => {
                        if let Some(运算符) = 运算符 {
                            // 复合赋值：按二元运算的规则检查（字符串 += 拼接同样适用）
                            let _ = 二元结果类型(*运算符, 现有类型, 值类型, 语句.行, 诊断);
                        } else {
                            检查可赋值(值类型, 现有类型, 语句.行, 诊断);
                        }
                    }
                }
            }
            语句种类::打印 { 参数, .. } => {
                for 表达式 in 参数 {
                    let _ = 检查表达式(表达式, 作用域, 函数表, 诊断);
                }
            }
            语句种类::返回(值) => match 值 {
                Some(表达式) => {
                    if 返回类型 == 类型::空 {
                        诊断.记录(
                            级别::错误,
                            错误类别::语义,
                            format!(
                                "函数『{}』的返回类型为『空』，不允许 返回 带值的表达式",
                                所在函数
                            ),
                            语句.行,
                            1,
                        );
                    } else {
                        let 值类型 = 检查表达式(表达式, 作用域, 函数表, 诊断);
                        检查可赋值(值类型, 返回类型, 语句.行, 诊断);
                    }
                }
                None => {
                    if 返回类型 != 类型::空 {
                        诊断.记录(
                            级别::错误,
                            错误类别::语义,
                            format!(
                                "函数『{}』的返回类型为『{}』，『返回』之后必须跟一个表达式",
                                所在函数,
                                返回类型.名字()
                            ),
                            语句.行,
                            1,
                        );
                    }
                }
            },
            语句种类::如果 {
                条件,
                分支,
                否则分支,
            } => {
                检查条件(条件, 作用域, 函数表, 诊断);
                检查语句块(分支, 作用域, 函数表, 所在函数, 返回类型, 循环深度, 诊断);
                检查语句块(否则分支, 作用域, 函数表, 所在函数, 返回类型, 循环深度, 诊断);
            }
            语句种类::当 { 条件, 循环体 } => {
                检查条件(条件, 作用域, 函数表, 诊断);
                检查语句块(循环体, 作用域, 函数表, 所在函数, 返回类型, 循环深度 + 1, 诊断);
            }
            语句种类::重复 { 次数, 循环体 } => {
                let 次数类型 = 检查表达式(次数, 作用域, 函数表, 诊断);
                if 次数类型 == 类型::字符串 {
                    诊断.记录(
                        级别::错误,
                        错误类别::语义,
                        "『重复』的次数不能是字符串（需要整数）",
                        语句.行,
                        1,
                    );
                }
                检查语句块(循环体, 作用域, 函数表, 所在函数, 返回类型, 循环深度 + 1, 诊断);
            }
            语句种类::跳出 => {
                if 循环深度 == 0 {
                    诊断.记录(
                        级别::错误,
                        错误类别::语义,
                        "『跳出』只能出现在循环（当 / 重复）内部",
                        语句.行,
                        1,
                    );
                }
            }
            语句种类::跳过 => {
                if 循环深度 == 0 {
                    诊断.记录(
                        级别::错误,
                        错误类别::语义,
                        "『跳过』只能出现在循环（当 / 重复）内部",
                        语句.行,
                        1,
                    );
                }
            }
            语句种类::表达式语句(表达式) => {
                let _ = 检查表达式(表达式, 作用域, 函数表, 诊断);
            }
        }
    }
}

/// 声明变量：同作用域重复声明 → 【符号重复定义】。
fn 声明变量(作用域: &mut 作用域, 变量名: &str, 类型: 类型, 行: usize, 诊断: &mut 诊断箱) {
    if let Some(&旧行) = 作用域.声明行.get(变量名) {
        诊断.记录(
            级别::错误,
            错误类别::语义,
            format!(
                "【符号重复定义】变量『{}』重复定义（先前定义在第 {} 行）",
                变量名, 旧行
            ),
            行,
            1,
        );
        return;
    }
    作用域.顺序.push(变量名.to_string());
    作用域.类型表.insert(变量名.to_string(), 类型);
    作用域.声明行.insert(变量名.to_string(), 行);
}

/// 检查表达式并推断其类型。
fn 检查表达式(
    表达式: &表达式,
    作用域: &作用域,
    函数表: &HashMap<String, 函数信息>,
    诊断: &mut 诊断箱,
) -> 类型 {
    match &表达式.种类 {
        表达式种类::整数字面量(_) => 类型::整数64,
        表达式种类::浮点字面量(_) => 类型::浮点数64,
        表达式种类::字符串字面量(_) => 类型::字符串,
        表达式种类::真 | 表达式种类::假 => 类型::布尔,
        表达式种类::变量(名) => match 作用域.类型表.get(名) {
            Some(&类型) => 类型,
            None => {
                诊断.记录(
                    级别::错误,
                    错误类别::语义,
                    format!(
                        "【变量未定义】使用了未定义的变量『{}』（请先使用 设 变量名 为 表达式 声明）",
                        名
                    ),
                    表达式.行,
                    表达式.列,
                );
                类型::整数64 // 占位类型，避免连锁错误
            }
        },
        表达式种类::取负(内) => {
            let 类型 = 检查表达式(内, 作用域, 函数表, 诊断);
            if 类型 == 类型::字符串 {
                诊断.记录(
                    级别::错误,
                    错误类别::语义,
                    "字符串类型不能取负（第一版字符串不参与算术运算）",
                    表达式.行,
                    表达式.列,
                );
                return 类型::整数64;
            }
            类型
        }
        表达式种类::二元 { 运算符, 左, 右 } => {
            let 左类型 = 检查表达式(左, 作用域, 函数表, 诊断);
            let 右类型 = 检查表达式(右, 作用域, 函数表, 诊断);
            二元结果类型(*运算符, 左类型, 右类型, 表达式.行, 诊断)
        }
        表达式种类::逻辑且 { 左, 右 } => {
            let 左类型 = 检查表达式(左, 作用域, 函数表, 诊断);
            let 右类型 = 检查表达式(右, 作用域, 函数表, 诊断);
            检查逻辑操作数(左类型, 右类型, "逻辑与（&& / 与）", 表达式, 诊断);
            类型::布尔
        }
        表达式种类::逻辑或 { 左, 右 } => {
            let 左类型 = 检查表达式(左, 作用域, 函数表, 诊断);
            let 右类型 = 检查表达式(右, 作用域, 函数表, 诊断);
            检查逻辑操作数(左类型, 右类型, "逻辑或（|| / 或）", 表达式, 诊断);
            类型::布尔
        }
        表达式种类::逻辑非(内) => {
            let 类型 = 检查表达式(内, 作用域, 函数表, 诊断);
            if 类型 == 类型::字符串 {
                诊断.记录(
                    级别::错误,
                    错误类别::语义,
                    "字符串不能参与逻辑运算（非 / !）",
                    表达式.行,
                    表达式.列,
                );
            }
            类型::布尔
        }
        表达式种类::调用 { 函数名, 参数 } => match 函数表.get(函数名) {
            None => {
                诊断.记录(
                    级别::错误,
                    错误类别::语义,
                    format!("调用了未定义的函数『{}』", 函数名),
                    表达式.行,
                    表达式.列,
                );
                for 实参 in 参数 {
                    let _ = 检查表达式(实参, 作用域, 函数表, 诊断);
                }
                类型::整数64
            }
            Some(信息) => {
                if 参数.len() != 信息.参数类型.len() {
                    诊断.记录(
                        级别::错误,
                        错误类别::语义,
                        format!(
                            "【参数数量不匹配】函数『{}』期望 {} 个参数，但传入了 {} 个",
                            函数名,
                            信息.参数类型.len(),
                            参数.len()
                        ),
                        表达式.行,
                        表达式.列,
                    );
                }
                for (实参, 形参类型) in 参数.iter().zip(信息.参数类型.iter()) {
                    let 实参类型 = 检查表达式(实参, 作用域, 函数表, 诊断);
                    检查可赋值(实参类型, *形参类型, 实参.行, 诊断);
                }
                信息.返回类型
            }
        },
    }
}

/// 二元运算的结果类型与合法性：
/// 字符串只允许 + 拼接与全部六种比较（比较两侧都必须是字符串）；
/// 取余仅支持整数；其余与数值运算规则一致。
fn 二元结果类型(
    运算符: 二元运算符,
    左类型: 类型,
    右类型: 类型,
    行: usize,
    诊断: &mut 诊断箱,
) -> 类型 {
    let 涉及字符串 = 左类型 == 类型::字符串 || 右类型 == 类型::字符串;
    if 涉及字符串 {
        return match 运算符 {
            二元运算符::加 => 类型::字符串,
            二元运算符::等于
            | 二元运算符::不等于
            | 二元运算符::小于
            | 二元运算符::大于
            | 二元运算符::小于等于
            | 二元运算符::大于等于 => {
                if 左类型 == 类型::字符串 && 右类型 == 类型::字符串 {
                    类型::布尔
                } else {
                    诊断.记录(
                        级别::错误,
                        错误类别::语义,
                        "字符串只能与字符串做比较（与数值比较没有意义）",
                        行,
                        1,
                    );
                    类型::布尔
                }
            }
            _ => {
                诊断.记录(
                    级别::错误,
                    错误类别::语义,
                    "字符串只支持 + 拼接与 == / != / < / > / <= / >= 比较（- * / % 等不适用）",
                    行,
                    1,
                );
                类型::整数64
            }
        };
    }
    if 运算符 == 二元运算符::取余
        && (左类型 == 类型::浮点数64 || 右类型 == 类型::浮点数64)
    {
        诊断.记录(
            级别::错误,
            错误类别::语义,
            "取余 % 仅支持整数运算",
            行,
            1,
        );
        return 类型::整数64;
    }
    if 运算符.是比较() {
        类型::布尔
    } else if 左类型 == 类型::浮点数64 || 右类型 == 类型::浮点数64 {
        类型::浮点数64
    } else {
        类型::整数64
    }
}

/// 检查逻辑运算的操作数：不能是字符串。
fn 检查逻辑操作数(左类型: 类型, 右类型: 类型, 运算名: &str, 表达式: &表达式, 诊断: &mut 诊断箱) {
    if 左类型 == 类型::字符串 || 右类型 == 类型::字符串 {
        诊断.记录(
            级别::错误,
            错误类别::语义,
            format!("字符串不能参与逻辑运算（{}）", 运算名),
            表达式.行,
            表达式.列,
        );
    }
}

/// 检查 如果/当 的条件：不能是字符串。
fn 检查条件(
    条件: &表达式,
    作用域: &作用域,
    函数表: &HashMap<String, 函数信息>,
    诊断: &mut 诊断箱,
) {
    let 类型 = 检查表达式(条件, 作用域, 函数表, 诊断);
    if 类型 == 类型::字符串 {
        诊断.记录(
            级别::错误,
            错误类别::语义,
            "『如果』/『当』的条件不能是字符串",
            条件.行,
            条件.列,
        );
    }
}

/// 检查赋值/传参的类型相容性：字符串与数值之间不允许，整数与浮点之间自动转换。
fn 检查可赋值(来源: 类型, 目标: 类型, 行: usize, 诊断: &mut 诊断箱) {
    let 来源是字符串 = 来源 == 类型::字符串;
    let 目标是字符串 = 目标 == 类型::字符串;
    if 来源是字符串 != 目标是字符串 {
        诊断.记录(
            级别::错误,
            错误类别::语义,
            format!(
                "类型不兼容：不能把{}与{}互相赋值/传递（整数与浮点之间允许自动转换）",
                来源.名字(),
                目标.名字()
            ),
            行,
            1,
        );
    }
}
